#!/usr/bin/env bash
set -Eeuo pipefail
# Ubuntu Netplan IPv4 manager. Requires python3-yaml (normally installed with netplan).
[[ $EUID -eq 0 ]] || { echo 'Run as root: sudo bash ip-switcher.sh'; exit 1; }
command -v netplan >/dev/null || { echo 'Netplan is required.'; exit 1; }
python3 -c 'import yaml' 2>/dev/null || { echo 'Missing python3-yaml: apt install python3-yaml'; exit 1; }
IFACE=$(ip -4 route show default | awk 'NR==1 {for(i=1;i<=NF;i++)if($i=="dev")print $(i+1)}')
[[ -n "$IFACE" ]] || { echo 'No IPv4 default route found.'; exit 1; }
mapfile -t CONFIGS < <(find /etc/netplan -maxdepth 1 \( -name '*.yaml' -o -name '*.yml' \) -type f | sort)
[[ ${#CONFIGS[@]} -gt 0 ]] || { echo 'No Netplan YAML found.'; exit 1; }
# Locate the single file defining this interface; avoid silently changing multi-file overlays.
mapfile -t MATCHES < <(python3 - "$IFACE" "${CONFIGS[@]}" <<'PY'
import sys,yaml
for p in sys.argv[2:]:
    with open(p) as f: d=yaml.safe_load(f) or {}
    if sys.argv[1] in (d.get('network',{}).get('ethernets',{}) or {}): print(p)
PY
)
[[ ${#MATCHES[@]} -eq 1 ]] || { printf 'Expected one Netplan file defining %s; found %s. Aborting.\n' "$IFACE" "${#MATCHES[@]}"; exit 1; }
FILE=${MATCHES[0]}
if grep -qi 'generated by cloud-init' "$FILE"; then echo 'Warning: cloud-init may overwrite this file on reboot.'; fi
backup_dir=""
restore() {
  if [[ -n "$backup_dir" && -f "$backup_dir/original.yaml" ]]; then
    cp -a "$backup_dir/original.yaml" "$FILE"
    chmod 600 "$FILE"
    netplan generate && netplan apply || true
    echo "Restored configuration from $backup_dir"
  fi
}
change() {
  local mode=$1 value=$2
  backup_dir=$(mktemp -d /root/ip-switcher-backup.XXXXXXXX)
  cp -a "$FILE" "$backup_dir/original.yaml"
  echo "Backup: $backup_dir/original.yaml"
  if ! python3 - "$FILE" "$IFACE" "$mode" "$value" <<'PY'
import sys, yaml, ipaddress, os
path,iface,mode,value=sys.argv[1:]
with open(path) as f: data=yaml.safe_load(f)
eth=data['network']['ethernets'][iface]
if eth.get('dhcp4',False): sys.exit('DHCPv4 enabled; refusing to modify managed dynamic network')
addresses=eth.get('addresses',[])
if not isinstance(addresses,list): sys.exit('Unexpected Netplan addresses format')
if mode=='add':
    addr=ipaddress.ip_interface(value)
    if addr.version!=4: sys.exit('Only IPv4 supported')
    if any(isinstance(a,dict) for a in addresses): sys.exit('Advanced address format not supported')
    if not any(ipaddress.ip_interface(str(a)).ip==addr.ip for a in addresses if ':' not in str(a)):
        addresses.append(str(addr))
    eth['addresses']=addresses
elif mode=='switch':
    target=ipaddress.ip_address(value)
    if target.version!=4: sys.exit('Only IPv4 supported')
    if not any(ipaddress.ip_interface(str(a)).ip==target for a in addresses if isinstance(a,str) and ':' not in a):
        sys.exit('Selected IPv4 not found in Netplan addresses; refusing change')
    routes=eth.get('routes',[])
    defaults=[r for r in routes if isinstance(r,dict) and r.get('to') in ('default','0.0.0.0/0') and ':' not in str(r.get('via',''))]
    if len(defaults)!=1: sys.exit('Expected exactly one static IPv4 default route; refusing change')
    defaults[0]['from']=str(target)
else: sys.exit('Invalid mode')
tmp=path+'.ip-switcher.tmp'
with open(tmp,'w') as f: yaml.safe_dump(data,f,sort_keys=False,allow_unicode=True)
os.chmod(tmp,0o600)
os.replace(tmp,path)
PY
  then
    restore; return 1
  fi
  if ! netplan generate; then restore; return 1; fi
  echo 'Applying via netplan try (120 seconds). Confirm only if SSH/network works.'
  echo 'If disconnected, wait for automatic rollback. Use provider console if necessary.'
  if netplan try --timeout 120; then
    echo 'Netplan try finished. Current network:'
    ip -4 route show default
    ip -4 addr show dev "$IFACE"
    echo "Backup retained at: $backup_dir/original.yaml"
    backup_dir=""
  else
    echo 'Netplan try returned an error. Restoring original file.'
    restore
    return 1
  fi
}
while true; do
  echo; echo '=== Universal IPv4 Switcher ==='
  echo "Interface: $IFACE | Config: $FILE"
  echo 'Assigned IPv4:'
  ip -o -4 addr show dev "$IFACE" | awk '{print "  " $4}'
  echo 'Default route:'; ip -4 route show default
  echo '1) Select preferred outgoing IPv4 (already in Netplan)'
  echo '2) Add provider-assigned IPv4/CIDR (no gateway changes)'
  echo '0) Exit'
  read -rp 'Choice: ' choice
  case "$choice" in
    1) read -rp 'Existing IPv4 (without /mask): ' addr; change switch "$addr" ;;
    2) echo 'Only add an address already allocated and routed by your provider.'
       read -rp 'New IPv4/CIDR (e.g. 203.0.113.10/32): ' addr; change add "$addr" ;;
    0) exit 0 ;;
    *) echo 'Invalid selection.' ;;
  esac
done
